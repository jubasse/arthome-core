#!/usr/bin/env node
// arthome-check-decisions-index — DECISIONS-INDEX.md is a PROJECTION of DECISIONS.md, generated,
// never edited by hand.
//
// WHAT IT WRITES
//   One line per decision, in DECISIONS.md's own order: its id, its title and the documents its
//   entry cites — exactly as the entry spells them, no normalising a bare `data-model.md`
//   against `architecture/data-model.md`. 94 decisions and growing is too many to read whole for
//   one rule; an agent opens the index, finds the id, then opens `DECISIONS.md` at that heading
//   for the reason.
//
// HOW A DECISION'S BODY IS DELIMITED
//   From its own `### D-NNN — …` heading to the next heading of that or a higher level (`### ` or
//   `## `), or the end of the file.
//
// USAGE
//   node tools/check-decisions-index.mjs          — the gate: fails if DECISIONS-INDEX.md is stale
//   node tools/check-decisions-index.mjs --write   — regenerates DECISIONS-INDEX.md

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const CWD = process.cwd();
const DECISIONS_FILE = path.join(CWD, 'DECISIONS.md');
const INDEX_FILE = path.join(CWD, 'DECISIONS-INDEX.md');

const HEADING_RE = /^(#{2,3}) (\S+(?: \([^)]*\))?) — (.+)$/;
const CITATION_RE = /`([\w./-]+\.md)`/g;

function parseDecisions(text) {
  const lines = text.split('\n');
  const headings = [];
  for (let i = 0; i < lines.length; i += 1) {
    const m = HEADING_RE.exec(lines[i]);
    if (m) headings.push({ line: i, level: m[1].length, id: m[2], title: m[3] });
  }
  const decisions = [];
  for (let i = 0; i < headings.length; i += 1) {
    const h = headings[i];
    if (h.level !== 3 || !h.id.startsWith('D-')) continue;
    const next = headings.slice(i + 1).find((other) => other.level <= h.level);
    const end = next ? next.line : lines.length;
    const body = lines.slice(h.line, end).join('\n');
    const docs = [...new Set([...body.matchAll(CITATION_RE)].map((m) => m[1]))].sort();
    decisions.push({ id: h.id, title: h.title, docs });
  }
  return decisions;
}

function buildIndex(decisions) {
  const rows = decisions.map((d) => {
    const docs = d.docs.length ? d.docs.map((doc) => `\`${doc}\``).join(', ') : 'none';
    return `| ${d.id} | ${d.title} | ${docs} |`;
  });
  return [
    '# Decisions index',
    '',
    '> GENERATED by `node tools/check-decisions-index.mjs --write` from `DECISIONS.md` — DO NOT',
    '> EDIT. `pnpm run check:decisions-index` fails when this file differs from what regenerating',
    '> would produce. Open `DECISIONS.md` at the id for the reason behind a row.',
    '',
    `${decisions.length} decisions.`,
    '',
    '| Decision | Title | Documents cited |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const WRITE = args.includes('--write');
  const QUIET = args.includes('--quiet');

  if (!fs.existsSync(DECISIONS_FILE)) {
    console.error('FAIL arthome-check-decisions-index: DECISIONS.md not found.');
    process.exit(3);
  }

  const decisions = parseDecisions(fs.readFileSync(DECISIONS_FILE, 'utf8'));
  const generated = buildIndex(decisions);

  if (WRITE) {
    fs.writeFileSync(INDEX_FILE, generated);
    console.log(
      `arthome-check-decisions-index: wrote ${path.relative(CWD, INDEX_FILE)} — ${decisions.length} decision(s).`,
    );
    return;
  }

  const current = fs.existsSync(INDEX_FILE) ? fs.readFileSync(INDEX_FILE, 'utf8') : null;
  if (current === generated) {
    if (!QUIET) {
      console.log(
        `PASS DECISIONS-INDEX.md matches DECISIONS.md — ${decisions.length} decision(s).`,
      );
    }
    return;
  }

  console.error(
    current === null
      ? 'FAIL DECISIONS-INDEX.md does not exist.'
      : 'FAIL DECISIONS-INDEX.md is stale against DECISIONS.md.',
  );
  console.error('  Regenerate with: node tools/check-decisions-index.mjs --write');
  process.exit(1);
}

main();
